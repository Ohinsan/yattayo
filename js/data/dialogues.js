// ==========================================================================
// 💬 カジゴンのおしゃべりセリフ（時間帯・曜日・季節・家具・連続コンボ）
// ==========================================================================
function getExpandedCompanionLines(context) {
    const { lv, stage, now, totalDone, comboCount } = context;

    // 🥚 Task 3: 卵ステージ（Lv.1〜2 / STAGE: EGG）は人間の言葉を通さず状況描写・擬音のみ返す
    if (stage === 'egg' || (typeof lv === 'number' && lv <= 2)) {
        return [
            '（コトン…と中から音がした）',
            '（ほんのり温かい気配がする…）',
            '（ピキッ…！殻がわずかに揺れた）',
            '（静かに家事のパワーを吸収しているようだ…）'
        ];
    }

    const hour = now.getHours();
    const day = now.getDay(); // 0:Sun, 1:Mon, ..., 6:Sat
    const month = now.getMonth() + 1;
    const lines = [];

    // --- ⚡ 家事連続コンボ時のリアクション ---
    if (comboCount >= 3) {
        lines.push('「うおおっ！家事コンボ炸裂中だな！部屋が一瞬でピカピカになっていくぞ！」');
        lines.push('「止まらない怒涛の連撃！二人の連携プレー、完全に神がかってるぞ！」');
    }

    // --- ⏰ 時間帯別セリフ ---
    if (hour >= 5 && hour < 10) {
        lines.push('「おはよう！朝の澄んだ空気、気持ちいいね！朝イチの家事で今日も快調！」');
        lines.push('「朝から動いてて偉すぎるぞ…！今日も無理せずマイペースにいこう！」');
    } else if (hour >= 11 && hour < 14) {
        lines.push('「お昼ごはんの時間だね！お腹いっぱい食べて、午後もゆるりといこう！」');
        lines.push('「午前中の家事、ナイスファイト！ちょっと一息ついてお茶でも飲もう！」');
    } else if (hour >= 17 && hour < 21) {
        lines.push('「今日もお仕事や用事、お疲れさま！夜ご飯のいい匂いがしてきたぞ！」');
        lines.push('「夕方のひと踏ん張り、いつもありがとう！今夜はゆっくり休もうね。」');
    } else if (hour >= 21 || hour < 4) {
        lines.push('「夜遅くまで本当にお疲れさま…！無理しないで、あったかいお風呂に入って寝ようね。」');
        lines.push('「静かな夜のひと仕事、カジゴンはいつでも見てるぞ…すやすやzzz」');
    }

    // --- 📅 曜日別セリフ ---
    if (day === 1) { // 月曜
        lines.push('「月曜日だな！新しい1週間の始まり！気負わずのんびりスタートしよう！」');
    } else if (day === 5) { // 金曜
        lines.push('「花金だーー！今週も本当にお疲れさま！今夜は家事もそこそこに乾杯しようぜ！」');
    } else if (day === 6 || day === 0) { // 週末
        lines.push('「週末に家事やるなんて偉すぎるぞ…！綺麗なお部屋で過ごす休日は最高だな！」');
        lines.push('「ふたりで過ごす休日、おうちが居心地いいと心までほぐれるね〜！」');
    }

    // --- 🌸 季節別セリフ ---
    if (month >= 3 && month <= 5) {
        lines.push('「春の風が心地いいね！窓を大きく開けてお部屋の空気を入れ替えよう！」');
    } else if (month >= 6 && month <= 8) {
        lines.push('「夏本番！水分補給しっかりしながら、涼しい時間にササッとやろうぜ！」');
    } else if (month >= 9 && month <= 11) {
        lines.push('「秋の味覚が美味しい季節！キッチンからホクホクのご飯の香りがするぞ！」');
    } else {
        lines.push('「外は寒いけど、おうちの中はぬくぬく！こたつに入ってシチュー食べたいな！」');
    }

    // --- 🏡 部屋の家具・快適度リアクション ---
    if (totalDone >= 20) {
        lines.push('「シチュー鍋のいい匂いがするな…おうちの快適度、ぐんぐん上がってるぞ！」');
    }
    if (totalDone >= 32) {
        lines.push('「窓から見える星空がとってもキレイだね！この部屋が大好きだな〜！」');
    }
    if (totalDone >= 48) {
        lines.push('「黄金のトロフィーがピカピカ輝いてる！ふたりの努力の結晶だな！」');
    }

    // --- 🥚 成長段階別セリフ ---
    if (stage === 'baby') {
        lines.push('「ピピピッ！総監督、なでてくれてありがとう！抱っこして〜！」');
        lines.push('「もっといっぱい家事を覚えて、かっこいい守護精霊になりたいな！」');
    } else if (stage === 'teen') {
        lines.push('「ふふん、最近おうちがどんどんピカピカになってるの、ちゃんと気づいてるよ！」');
        lines.push('「どんな姿に進化するか楽しみだな〜！今の環境テーマ、すごく合ってる気がする！」');
    } else {
        lines.push('「我が主よ、いつもおうちを慈しみ、守ってくれて心から感謝いたします。」');
        lines.push('「この部屋の平和と清潔さは、あなたの毎日の細やかな愛の賜物です！」');
    }

    // 🗑️ ゴミ出しリマインダー
    const daysMap = ['日', '月', '火', '水', '木', '金', '土'];
    lines.push(`「今日は${daysMap[day]}曜日！忘れずにゴミ捨てチェックしておこう！」`);

    return lines;
}
